# Вектор — это просто цепочка чисел. У него только одно измерение.

my_vec <- c(10, 20, 30, 40, 50)

# А) По порядковому номеру (индексу)
val_1 <- my_vec[1]       # Достанет первое число (10)
val_3 <- my_vec[3]       # Достанет третье число (30)

# Б) Несколько элементов (через вектор индексов)
vals_multi <- my_vec[c(1, 4)]  # Достанет 1-е и 4-е число (10 и 40)
vals_seq <- my_vec[2:4]        # Достанет числа с 2-го по 4-е (20, 30, 40)

# В) Исключить элемент (ставим минус)
vec_without_first <- my_vec[-1] # Выведет всё, КРОМЕ первого элемента

# Г) По условию (очень частый трюк!)
vals_big <- my_vec[my_vec > 25] # Выдаст только те числа, которые больше 25 (30, 40, 50)


# =========================================================================
# 3. КАК ВЫБИРАТЬ ДАННЫЕ ИЗ ТАБЛИЦ (Data Frames)
# =========================================================================
# Таблица (data.frame) похожа на матрицу, но столбцы имеют имена, 
# и в них могут быть разные типы данных (текст, числа).

# Создадим небольшую тестовую таблицу
my_table <- data.frame(
  Name = c("Alice", "Bob", "Charlie"),
  Age = c(25, 30, 22),
  Score = c(85, 92, 88)
)

# А) Знак ДОЛЛАРА ($) — самый главный способ!
# Если тебе нужен целый столбец (он превратится в вектор):
ages <- my_table$Age       # Вытащит столбец Age: 25, 30, 22
scores <- my_table$Score   # Вытащит столбец Score: 85, 92, 88

# Б) Как в матрице [строка, столбец]
# Таблицы тоже поддерживают такой синтаксис:
val_df <- my_table[2, 3]       # Строка 2, столбец 3 (оценка Боба: 92)
row_df <- my_table[1, ]        # Вся первая строка (все данные про Алису)
col_df <- my_table[, "Score"]  # Весь столбец Score (альтернатива my_table$Score)

# В) Фильтрация строк по условию
# Например, нам нужны только те студенты (строки), у которых Age > 24
# Пишем условие ДО запятой, а ПОСЛЕ запятой оставляем пусто (чтобы взять все столбцы)
older_students <- my_table[my_table$Age > 24, ]