# --- 1. КАК ВЫБИРАТЬ ДАННЫЕ ИЗ МАТРИЦЫ ---
# Запомни главное правило: матрица[строка, столбец]

# Создадим тестовую матрицу для примеров
mat <- matrix(c(5, 2, 1, 
                3, 6, 3, 
                1, 2, 7), 
              nrow = 3, byrow = TRUE)
rownames(mat) <- c("1", "2", "3") # Имена строк (например, значения X)
colnames(mat) <- c("0", "1", "2") # Имена столбцов (например, значения Y)

# А) Одно конкретное значение
# Если нужно значение, где X=3 (строка "3") и Y=2 (столбец "2"):
val <- mat["3", "2"] 
# ВАЖНО: лучше всегда использовать имена строк/столбцов в кавычках. 
# Если написать mat[3, 2], R возьмет 3-ю строку и 2-й столбец по счету, 
# что может не совпадать со значениями X и Y!

# Б) Целая строка (оставляем пустое место ПОСЛЕ запятой)
row_2 <- mat["2", ]  # Вся строка, где X=2

# В) Целый столбец (оставляем пустое место ДО запятой)
col_1 <- mat[, "1"]  # Весь столбец, где Y=1

# Г) Несколько строк или столбцов (используем вектор c() )
sub_mat <- mat[c("1", "2"), c("1", "2")] # Кусочек матрицы (строки 1,2 и столбцы 1,2)

# Д) Суммирование
sum_all <- sum(mat)                # Сумма вообще всех ячеек в матрице
sum_row <- sum(mat["2", ])         # Сумма только одной строки
sum_cols <- sum(mat[, c("1", "2")])# Сумма ячеек в двух столбцах вместе


